#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_normalize_number_str_half_width() {
        assert_eq!(normalize_number_str("123"), "123");
        assert_eq!(normalize_number_str("-456"), "-456");
        assert_eq!(normalize_number_str("3.14"), "3.14");
    }

    #[test]
    fn test_normalize_number_str_full_width() {
        assert_eq!(normalize_number_str("１２３"), "123");
        assert_eq!(normalize_number_str("－４５６"), "-456");
        assert_eq!(normalize_number_str("３．１４"), "3.14");
    }

    #[test]
    fn test_normalize_number_str_mixed() {
        assert_eq!(normalize_number_str("１2３"), "123");
        assert_eq!(normalize_number_str("3．１４"), "3.14");
        assert_eq!(normalize_number_str("－123"), "-123");
    }

    #[test]
    fn test_parse_str_ignores_leading_bom() {
        let source = "＊挨拶\n  Alice：こんにちは\n";
        let plain = parse_str(source, "a.pasta").unwrap();
        let with_bom = parse_str(&format!("\u{FEFF}{source}"), "a.pasta").unwrap();
        assert_eq!(format!("{with_bom:?}"), format!("{plain:?}"));
    }

    #[test]
    fn test_syntax_error_builds_prefixed_message() {
        let err = syntax_error("dic/a.pasta", (2, 13), "範囲を超えています");
        assert_eq!(
            format!("{err:?}"),
            format!(
                "{:?}",
                ParseError::SyntaxError {
                    file: "dic/a.pasta".to_string(),
                    line: 2,
                    column: 13,
                    message: "Parse error in dic/a.pasta at 2:13: 範囲を超えています".to_string(),
                }
            )
        );
    }

    #[test]
    fn test_try_parse_expr_rejects_unhandled_rule_with_position() {
        // 2 行目の話者名 `Alice`（id 規則）は式の項ではない
        let source = "＊挨拶\n  Alice：こんにちは\n";
        let pair = PastaParser2::parse(Rule::file, source)
            .unwrap()
            .flatten()
            .find(|p| p.as_rule() == Rule::id && p.as_str() == "Alice")
            .unwrap();
        let err = try_parse_expr(pair, "dic/a.pasta").unwrap_err();
        assert_eq!(
            format!("{err:?}"),
            format!(
                "{:?}",
                syntax_error(
                    "dic/a.pasta",
                    (2, 3),
                    "内部の誤り：式の項として扱えない規則 id"
                )
            )
        );
    }

    #[test]
    fn test_is_id() {
        for s in ["名前", "_x", "x1", "r0", "ｒ０", "天気"] {
            assert!(is_id(s), "{s}");
        }
        for s in [
            "",
            "1",
            "１",
            "__名前__",
            "a b",
            "a-b",
            "a.b",
            "名前、",
            "★",
        ] {
            assert!(!is_id(s), "{s}");
        }
    }

    #[test]
    fn test_pest_parser_compiles() {
        // Verify that PastaParser2 can parse the file rule
        let result = PastaParser2::parse(Rule::file, "");
        assert!(result.is_ok());
    }
}
